using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace StudentScoreTool;

public static class TextNormalization
{
    private static readonly Dictionary<char, char> TraditionalToSimplified = CreateTraditionalMap();

    public static string ToHalfWidth(string? value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return string.Empty;
        }

        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(ToHalfWidth(ch));
        }

        return builder.ToString();
    }

    public static char ToHalfWidth(char ch)
    {
        if (ch == '\u3000')
        {
            return ' ';
        }

        if (ch is >= '\uFF01' and <= '\uFF5E')
        {
            return (char)(ch - 0xFEE0);
        }

        return ch;
    }

    public static string DisplayText(string? value)
    {
        var text = ToHalfWidth(value);
        text = text.Replace('\u00A0', ' ').Replace('\u2007', ' ').Replace('\u202F', ' ');
        return Regex.Replace(text.Trim(), @"\s+", " ");
    }

    public static string ToSimplified(string? value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return string.Empty;
        }

        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(TraditionalToSimplified.TryGetValue(ch, out var simplified) ? simplified : ch);
        }

        return builder.ToString();
    }

    public static string NormalizeName(string? value)
    {
        var text = ToSimplified(ToHalfWidth(value));
        text = text.Replace('\u00A0', ' ');
        text = UnifyNameDots(text);
        text = Regex.Replace(text, @"[（(【\[][^）)】\]]*[）)】\]]", string.Empty);
        text = Regex.Replace(text, @"\s+", string.Empty);
        return text.Trim();
    }

    public static string NormalizeId(string? value)
    {
        var text = ToHalfWidth(value);
        text = Regex.Replace(text, @"\s+", string.Empty);
        text = text.ToUpperInvariant();
        if (text.Length == 0)
        {
            return string.Empty;
        }

        text = text.TrimStart('0');
        return text.Length == 0 ? "0" : text;
    }

    public static string UnifyNameDots(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(ch is '\u00B7' or '\u2022' or '\u30FB' or '\u2027' or '\uFF0E' or '\u2219' or '\u2024' or '\u30A0'
                ? '\u00B7'
                : ch);
        }

        return builder.ToString();
    }

    public static bool TryParseScoreNumber(string? value, out double number)
    {
        var text = DisplayText(value);
        if (text.Length == 0)
        {
            number = 0;
            return false;
        }

        return double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out number)
            || double.TryParse(text, NumberStyles.Float, CultureInfo.GetCultureInfo("zh-CN"), out number);
    }

    public static bool IsNumericScoreOutOfRange(double number) => number is < 0 or > 150;

